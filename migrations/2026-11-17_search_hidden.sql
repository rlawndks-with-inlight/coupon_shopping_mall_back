-- ============================================================================
-- 검색 노출 끄기 — 시험·견본 몰을 검색엔진에서 뺀다
-- 날짜: 2026-11-17  (사장님 결정: 켜 둘 몰은 샵고 메인(98)·포스몰(99)·해담수산(141)뿐,
--                    포항과메기(130)·첫돌공방(105)도 시험용이라 끈다. 새 몰은 기본 켜짐)
--
-- 값: brands.seo_obj(varchar, JSON 글자) 에 "search_hidden": true 를 더한다. 칸 추가 없음.
--     naver_token·google_token 등 기존 키는 그대로 둔다(JSON_SET).
--     끈 몰은 프론트가 모든 페이지 noindex · robots.txt 전부 막기 · 빈 사이트맵을 낸다.
--     관리자 SEO설정 탭의 「검색엔진 노출」 스위치와 같은 값이다.
--
-- 대상: 본사(98) 아래 shopgo.co.kr 부주소 몰 중 위 두 곳(99·141)을 뺀 나머지 + 본사 밖 시험 몰 140.
--       다른 프로젝트 브랜드(2~97)는 건드리지 않는다(이 DB 를 함께 쓴다).
-- ▶ 여러 번 돌려도 같은 결과다.
-- ============================================================================

-- 돌리기 전에 대상 확인
SELECT id, name, dns, seo_obj FROM brands
 WHERE is_delete = 0
   AND id IN (100,101,102,103,104,105,106,107,108,109,110,111,112,113,114,115,116,117,118,
              119,120,121,122,123,124,125,126,127,128,129,130,131,132,133,134,135,140);

UPDATE brands
   SET seo_obj = JSON_SET(IF(JSON_VALID(seo_obj), seo_obj, '{}'), '$.search_hidden', CAST('true' AS JSON))
 WHERE is_delete = 0
   AND id IN (100,101,102,103,104,105,106,107,108,109,110,111,112,113,114,115,116,117,118,
              119,120,121,122,123,124,125,126,127,128,129,130,131,132,133,134,135,140);

-- 확인: 켜진 몰은 98·99·141 만 남아야 한다
SELECT id, name, dns,
       IF(JSON_VALID(seo_obj) AND JSON_EXTRACT(seo_obj, '$.search_hidden') = TRUE, '끔', '켜짐') AS 검색노출
  FROM brands
 WHERE is_delete = 0 AND (id = 98 OR parent_id = 98 OR id = 140)
 ORDER BY 검색노출 DESC, id;
