-- 배송 요청사항 — 주문에 한 줄 남긴다.
--
-- 왜 필요한가(가맹점 요청 2026-08-21):
--   "정수기 함에 넣어주세요" 같은 배송 메모를 받을 자리가 주문서에 아예 없었다.
--   고객은 적을 곳이 없어 전화로 말하거나 그냥 포기했고, 가맹점은 주문마다 따로 물어야 했다.
--   상품별 「주문서 입력항목」으로 우회할 수는 있으나 그건 상품에 걸리는 값이라
--   '이 배송 건'의 요청사항으로는 맞지 않는다(같은 주문에 상품이 여럿이면 여러 번 묻는다).
--
-- 왜 주문에 박아 두나:
--   주소록 행은 나중에 고쳐지거나 지워진다. '그때 뭐라고 부탁했는지'는 주문 자체에 남아야
--   나중에 배송 사고를 확인할 수 있다(receiver·addr 을 주문에 복사해 두는 것과 같은 이유).
--
-- 길이: 255. 택배사 송장 요청사항란이 대개 50자 안팎이라 넉넉하다.
--   화면에서도 200자로 제한한다(프론트 OrderSheet).
--
-- 안전: 컬럼이 없어도 주문 저장은 그대로 된다(pay.controller 가 hasColumn 으로 건너뛴다).
--   즉 이 마이그레이션은 배포 전후 아무 때나 돌려도 되고, 안 돌리면 메모만 저장되지 않는다.

ALTER TABLE transactions
  ADD COLUMN delivery_memo VARCHAR(255) NULL DEFAULT NULL COMMENT '배송 요청사항(고객 입력)'
  AFTER detail_addr;
