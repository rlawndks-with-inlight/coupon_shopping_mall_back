// 분류에 안 걸린 문구는 원문 그대로 보여 준다. 다만 손님에게 보이면 안 되는 것만 막고 일반 문구로 대신한다 —
// 포스페이가 SQL 원문을 보낸 적이 있고(scripts/checks/pg-message.mjs), 긴 숫자는 전화번호·계좌번호일 수 있다.
const 보여도됨 = (s) => !!s && s.length <= 150
    && !/[{}<>=;`$]|SQL|exception|https?:|\d[\d\s-]{6,}/i.test(s);

// 반환: { 분류, 문구, 취소, 확인필요 } — 취소면 문구는 비운다(취소 화면은 사유를 보여 주지 않는다).
// 확인필요: 결제사가 「결제됐는지 앱에서 확인하라」고 한 경우(위챗페이 9998). 실패가 아니라 결과를 모르는 상태라
// 판정이 확인 중(0001)으로 보낸다 — 결과 화면이 거래조회를 더 해 보고, 그래도 모르면 「결제 확인이 늦어지고 있습니다」.
export const 실패사유분류 = (code, message) => {
    const c = String(code ?? '').trim();
    const s = (typeof message === 'string' ? message : '').replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
    if (취소코드.includes(c)) return { 분류: '취소', 문구: '', 취소: true };
    const 붙인글 = s.replace(/\s+/g, '');
    const 찾음 = 규칙.find(([, re]) => re.test(붙인글))?.[0];
    if (찾음 === '취소') return { 분류: '취소', 문구: '', 취소: true };
    if (찾음) return { 분류: 찾음, 문구: 실패문구[찾음], 취소: false, 확인필요: 찾음 === '결제확인' };
    // PV 코드는 포스페이 연동 코드라 원문(「pay key가 존재하지 않습니다」 등)을 손님에게 보이지 않는다 — 문서의 뜻으로만
    if (/^PV/i.test(c)) {
        const 분류 = PV분류[c.toUpperCase()] || '거절';
        return { 분류, 문구: 실패문구[분류], 취소: false };
    }
    if (보여도됨(s)) return { 분류: '원문', 문구: s, 취소: false };
    return { 분류: '거절', 문구: 실패문구.거절, 취소: false };
};
